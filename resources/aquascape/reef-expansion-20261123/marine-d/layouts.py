"""Source-board traces for the seaweed and seagrass models.

Front landmarks define elevation and broad form; opposite side/top/bottom
constrain depth, blade twists and attachment. Centers below are hand aligned
guide stations, not an attempted numerical reconstruction of occluded blades.
"""

def profile(points,widths,depths,twists):
    return [[*point,w,d,a] for point,w,d,a in zip(points,widths,depths,twists)]


def part(name,track,widths,patch="stem",depth=None,turn=None,**opts):
    depth = widths if depth is None else depth
    turn = [0.0]*len(track) if turn is None else turn
    return {"name":name,"patch":patch,"profile":profile(track,widths,depth,turn),**opts}


def blade(name,track,width,turn,patch="blade",rim=None,**opts):
    rim = [.10,.79,1,.06] if rim is None else rim
    return part(name,track,[width*t for t in rim],patch,
                depth=[width*(.045+.032*t) for t in rim],turn=turn,**opts)


def smooth(item,count):
    stations=item["profile"]
    rows=[]
    def extrapolate(a,b):
        return [2*x-y for x,y in zip(a,b)]
    controls=[extrapolate(stations[0],stations[1]),*stations,extrapolate(stations[-1],stations[-2])]
    for j in range(count):
        sample=(len(stations)-1)*j/(count-1)
        index=min(len(stations)-2,int(sample))
        t=sample-index
        a,b,c,d=controls[index:index+4]
        values=[]
        for i,(x,y,z,w) in enumerate(zip(a,b,c,d)):
            # Smooth the center path but keep cross-section widths monotone
            # between drawing landmarks.
            if i<3:
                values.append(0.5*((2*y)+(-x+z)*t+(2*x-5*y+4*z-w)*t*t+(-x+3*y-3*z+w)*t*t*t))
            else:
                values.append(y+(z-y)*t)
        rows.append(values)
    item["profile"]=rows
    return item


def lerp(a,b,t):
    return tuple(x+(y-x)*t for x,y in zip(a,b))


