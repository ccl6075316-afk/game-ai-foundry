def subdivide(vertices,faces):
    points=list(vertices)
    midpoint={}
    def at(a,b):
        key= min(a,b),max(a,b)
        if key not in midpoint:
            midpoint[key]=len(points)
            points.append((vertices[a]+vertices[b])*.5)
        return midpoint[key]
    refined=[]
    for a,b,c in faces:
        ab,bc,ca=at(a,b),at(b,c),at(c,a)
        refined.extend(((a,ab,ca),(ab,b,bc),(ca,bc,c),(ab,bc,ca)))
    return np.asarray(points,np.float32),np.asarray(refined,np.int32)

def sculpt(key,verts,faces):

    v,f=subdivide(verts,faces)
    lo=v.min(0)
    size=np.ptp(v,axis=0)
    unit=(v-lo)/size
    triangle=v[f]
    cross=np.cross(triangle[:,1]-triangle[:,0],triangle[:,2]-triangle[:,0])
    norms=np.zeros_like(v)
    for i in range(3):
        np.add.at(norms,f[:,i],cross)
    norms/=np.maximum(np.linalg.norm(norms,axis=1,keepdims=True),1e-12)
    shifts=np.zeros(len(v),np.float32)
    for center, radius, amplitude in ZONES[key]:
        base=np.asarray(center)
        if key in ("lava_rock","dragon_stone") and amplitude<0:
            dominant=int(np.argmax(abs(base-.5)))
            face=1 if base[dominant]>.5 else -1
            axes=[i for i in range(3) if i!=dominant]
            closest=np.linalg.norm((unit[:,axes]-base[axes])/np.asarray(radius)[axes],axis=1)
            facing=(norms[:,dominant]*face>.42) & (closest<.78)
            score=np.where(facing,closest - .21*face*unit[:,dominant],np.inf)
            if np.isfinite(score).any():
                base=unit[int(np.argmin(score))].copy()
                amplitude*=1.65
        d=np.linalg.norm((unit-base)/radius,axis=1)
        shifts+=amplitude*np.exp(-.5*d*d)
    shifts*=np.clip((unit[:,1]-.035)/.13,0.,1.)
    max_recess = .218 if key in ("lava_rock","dragon_stone") else .13
    shifts=np.clip(shifts,-max_recess,.15)*min(size[0],size[2])
    output=v+shifts[:,None]*norms
    output[:,1]=np.maximum(output[:,1],lo[1])
    return output,f,shifts
