"""Plan a bounded aquascape cleanup; verify retained evidence after shell deletion.

This command never deletes files. The plan lists exact absolute paths and hashes
for a native PowerShell executor to recheck. Other work lines are out of scope.
"""
import argparse
import hashlib
import json
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path


def read(path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    fish = root / "projects/fishing-2d"
    review = fish / "plans/reviews/aquascape-session-retention"
    review.mkdir(parents=True, exist_ok=True)
    plan_path = review / "cleanup-plan.json"
    report_path = review / "validation-report.json"
    if args.verify:
        plan = read(plan_path)
        missing = [p for p, h in plan["protected_hashes"].items()
                   if not (root / p).is_file() or sha(root / p) != h]
        remaining = [r["path"] for r in plan["remove"] if Path(r["path"]).exists()]
        okay = not missing and not remaining
        report = {"schema_version": 1, "command": "aquascape.session-retention",
                  "ok": okay, "status": "done" if okay else "failed",
                  "next_action": "human_review" if okay else "fix_input",
                  "at": datetime.now(timezone.utc).isoformat(),
                  "deleted_files": len(plan["remove"]),
                  "deleted_bytes": sum(r["bytes"] for r in plan["remove"]),
                  "protected_files": len(plan["protected_hashes"]),
                  "deletion_reasons": dict(Counter(r["reason"] for r in plan["remove"])),
                  "historical_reviews": plan["historical_reviews"],
                  "outputs": {"deletion_receipt": str(plan_path)},
                  "limitations": ["Only this conversation's aquascape/hall files are in scope.",
                                   "Earlier reports are historical receipts, not renewed acceptance; removed replay intermediates are listed explicitly.",
                                   "User acceptance of the hall wall appearance remains pending."],
                  "failures": {"changed_protected": missing, "not_deleted": remaining}}
        report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
        print(json.dumps({k: v for k, v in report.items() if k not in ["historical_reviews"]}))
        return 0 if okay else 1

    current = ["aquascape-edge-rebuild-v8", "aquarium-hall-style-v3",
               "aquascape-decor-v1", "aquascape-substrates-v2",
               "aquascape-sand-v1", "aquascape-marine-v1"]
    # Freeze the actual current bytes, not a false claim that all older hashes
    # survived subsequent work. Historical reports retain their original hashes.
    protected = {}
    for name in current:
        report = read(fish / "plans/reviews" / name / "validation-report.json")
        for rel in report.get("hashes", {}):
            path = root / rel
            if path.is_file():
                protected[rel] = sha(path)
    source_projects = [p for p in (root / "projects").iterdir()
                       if p.is_dir() and p.name.startswith(("aquascape-", "aquarium-hall-materials-"))]
    candidates = {}

    def candidate(path, reason):
        path = path.resolve()
        if path.is_symlink() or not path.is_file():
            return
        rel = path.relative_to(root).as_posix()
        if rel not in protected:
            candidates[path] = reason

    for project in source_projects:
        for path in project.rglob("*"):
            if not path.is_file():
                continue
            rel = path.relative_to(project)
            if rel.parts[0] == "game":
                candidate(path, "autogenerated-source-project-game-cache")
            elif path.suffix in [".log", ".jsonl"]:
                candidate(path, "completed-source-job-log")
            elif "rejected" in path.as_posix().lower() and path.suffix == ".png":
                candidate(path, "superseded-source-camera-attempt")

    assets = fish / "game/assets"
    for name in ["aquascape-v5/plant-static", "aquascape-v7/plant-static"]:
        for path in (assets / name).rglob("*"):
            candidate(path, "regenerable-duplicate-static-plant")
    for name in ["aquascape-v5/plants", "aquascape-v6/plants"]:
        for path in (assets / name).rglob("*"):
            if path.suffix in [".glb", ".import"] or "fallback" in path.name:
                candidate(path, "superseded-plant-model-intermediate")

    historical = []
    for directory in (fish / "plans/reviews").iterdir():
        if not directory.is_dir() or not directory.name.startswith(("aquascape-", "aquarium-hall-")):
            continue
        if directory == review:
            continue
        old = directory / "validation-report.json"
        if old.exists():
            data = read(old)
            historical.append({"path": old.relative_to(root).as_posix(),
                               "original_sha256": sha(old), "recorded_ok": data.get("ok"),
                               "summary": data.get("summary", {}),
                               "limitations": data.get("limitations", [])})
        for path in directory.rglob("*"):
            if not path.is_file():
                continue
            parts = path.relative_to(directory).parts
            if any(p in ["frames", "detail-frames"] for p in parts[:-1]):
                candidate(path, "dense-video-input-frame")
            elif directory.name in ["aquascape-leaf-edges-v6", "aquascape-leaf-contours-v7"] and parts[0] == "godot" and path.suffix == ".png":
                candidate(path, "superseded-individual-review-view")
            elif path.suffix == ".log" and not path.name.startswith("interactive"):
                candidate(path, "redundant-capture-log")

    rows = [{"path": str(p), "relative": p.relative_to(root).as_posix(),
             "bytes": p.stat().st_size, "sha256": sha(p), "reason": reason}
            for p, reason in sorted(candidates.items())]
    for item in historical:
        prefix = str((root / item["path"]).parent)
        item["removed_local_files"] = sum(r["path"].startswith(prefix + "\\") for r in rows)
    plan = {"schema_version": 1, "command": "aquascape.plan-session-retention",
            "root": str(root), "allowed_source_roots": [str(p) for p in source_projects],
            "allowed_fish_roots": [str(assets), str(fish / "plans/reviews")],
            "protected_hashes": protected, "historical_reviews": historical, "remove": rows}
    plan_path.write_text(json.dumps(plan, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"ok": True, "plan": str(plan_path), "files": len(rows),
                      "bytes": sum(r["bytes"] for r in rows), "protected": len(protected),
                      "reasons": dict(Counter(r["reason"] for r in rows))}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
